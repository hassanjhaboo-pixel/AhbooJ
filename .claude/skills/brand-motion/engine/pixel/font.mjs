const glyph = ch => G[ch] || G[ch.toUpperCase()] || G['?'];
export const LINE_H = 10;   // cap 7 + descender 2 + 1 leading
export function charWidth(ch) { return glyph(ch)[0].length; }
export function textWidth(s) { let w = 0; for (const ch of s) w += charWidth(ch) + 1; return Math.max(0, w - 1); }
// word-wrap to a pixel width; returns array of lines
export function wrap(s, maxW) {
  const out = []; let cur = '';
  for (const word of s.split(' ')) { const t = cur ? cur + ' ' + word : word; if (textWidth(t) <= maxW || !cur) cur = t; else { out.push(cur); cur = word; } }
  if (cur) out.push(cur); return out;
}
// draw (optionally only the first `upto` characters) at integer pixel scale
export function drawText(ctx, s, x, y, color, o = {}) {
  const k = o.scale || 1; let cx = x, n = 0;
  const run = (col, dx, dy) => { cx = x; n = 0; ctx.fillStyle = col; for (const ch of s) { if (o.upto != null && n >= o.upto) break; const g = glyph(ch);
    for (let r = 0; r < g.length; r++) for (let c = 0; c < g[r].length; c++) if (g[r][c] === '#') ctx.fillRect(Math.round(cx + (c + dx) * k), Math.round(y + (r + dy) * k), k, k);
    cx += (g[0].length + 1) * k; n++; } };
  if (o.shadow) run(o.shadow, 1, 1);
  run(color, 0, 0);
  return cx - x;
}
